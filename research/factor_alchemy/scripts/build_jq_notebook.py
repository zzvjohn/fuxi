"""
生成 JQ 研究笔记本
从 registry 读取现有实现 + 为占位符生成新实现 → 输出完整 .py 笔记本
"""
import sys, textwrap
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from jq_generator.registry import JQ_FACTOR_REGISTRY

# 占位符因子实现 (从 generate_jq_notebook.py import)
sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_jq_notebook import PRICE_FACTOR_IMPLS, FUNDAMENTAL_FACTOR_IMPLS, NEUT_FACTORS, COMPLEX_SKIP

OUTPUT = Path(__file__).resolve().parent.parent / 'output' / 'jq_research_notebook.py'

# 收集所有因子
ALL_FACTORS = {}  # name -> {func_body, direction}

for name, meta in JQ_FACTOR_REGISTRY.items():
    func = meta.get('jq_compute_function', '')
    is_real = 'return np.full' not in func and 'Auto-generated placeholder' not in func and len(func.strip()) > 100

    if is_real:
        ALL_FACTORS[name] = {'func': func.strip(), 'direction': meta.get('direction', 1)}
    elif name in PRICE_FACTOR_IMPLS:
        impl = PRICE_FACTOR_IMPLS[name]
        # dedent first (templates have 4sp indent), then re-indent
        clean = textwrap.dedent(impl).strip()
        ALL_FACTORS[name] = {'func': f'def compute_{name}(stocks, price_data):\n{textwrap.indent(clean, "    ")}',
                            'direction': meta.get('direction', 1)}
    elif name in FUNDAMENTAL_FACTOR_IMPLS:
        impl = FUNDAMENTAL_FACTOR_IMPLS[name]
        clean = textwrap.dedent(impl).strip()
        ALL_FACTORS[name] = {'func': f'def compute_{name}(stocks, price_data):\n{textwrap.indent(clean, "    ")}',
                            'direction': meta.get('direction', 1)}
    elif name in NEUT_FACTORS:
        base = name.replace('_neut', '')
        if base in ALL_FACTORS:
            ALL_FACTORS[name] = {'func': f'def compute_{name}(stocks, price_data):\n    arr, valid = compute_{base}(stocks, price_data)\n    return arr, valid  # TODO: add sector neutralization',
                                'direction': meta.get('direction', 1)}
    elif name in COMPLEX_SKIP:
        ALL_FACTORS[name] = {'func': f'def compute_{name}(stocks, price_data):\n    n = len(stocks)\n    arr = np.full(n, np.nan)\n    return arr, np.full(n, False)  # Not implemented on JQ',
                            'direction': meta.get('direction', 1)}

print(f'Total factors: {len(ALL_FACTORS)} (from registry {len(JQ_FACTOR_REGISTRY)})')

# ═══════════════════════════════════════════
# 生成笔记本
# ═══════════════════════════════════════════

lines = []
def L(s=''):
    lines.append(s)

L('''"""
JQ 研究笔记本: Regime-Lasso 因子选择
======================================
在 JQ 研究平台运行此文件:
  1. 全量因子计算 (price + fundamentals)
  2. Regime 检测 (large_dominant / small_bull)
  3. ElasticNetCV per regime 因子选择
  4. 输出因子权重 → 复制到本地, 用 JQGenerator 生成策略

注意: 需要 JQData 付费版 (2021-2026 全量数据)
"""
''')

# ═══ Cell 1: Imports ═══
L('# Cell 1: Imports & Setup')
L('import numpy as np')
L('import pandas as pd')
L('try:')
L('    from jqdata import *')
L('except ImportError:')
L('    from jqdatasdk import *')
L('from scipy.stats import spearmanr')
L('from sklearn.linear_model import ElasticNetCV')
L('from sklearn.preprocessing import StandardScaler')
L('import warnings')
L('warnings.filterwarnings("ignore")')
L('')
L('# 配置')
L('START_DATE = "2021-01-01"')
L('END_DATE = "2026-06-30"')
L('TOP_N = 30')
L('WEEKDAY = 5  # 周五调仓')
L('LOOKBACK_DAYS = 260  # 因子计算回看天数')
L('')
L('# Regime 检测阈值')
L('STYLE_SPREAD_THRESHOLD = 0.02   # CSI500-CSI300 > 2% = small_bull')
L('TREND_THRESHOLD = -0.01         # CSI_ALL > -1% = 上涨')
L('')
L('print("✓ Setup complete")')

# ═══ Cell 2: 获取股票池 ═══
L('')
L('# Cell 2: 获取股票池')
L('def get_stock_pool():')
L('    """获取全A股股票池 (剔除ST/退市/新股)"""')
L('    all_securities = get_all_securities(["stock"], date=END_DATE)')
L('    pool = []')
L('    for code, row in all_securities.iterrows():')
L('        # 剔除ST/退市 (名称含ST或退)')
L('        name = str(row.get("display_name", ""))')
L('        if "ST" in name or "退" in name or "*" in name[:3]:')
L('            continue')
L('        # 剔除上市不足180天')
L('        days_listed = (pd.Timestamp(END_DATE) - pd.Timestamp(row["start_date"])).days')
L('        if days_listed > 180:')
L('            pool.append(code)')
L('    return pool')
L('')
L('ALL_STOCKS = get_stock_pool()')
L('print(f"Stock pool: {len(ALL_STOCKS)} stocks")')
L('print("Sample:", ALL_STOCKS[:5])')

# ═══ Cell 3: 加载价格数据 ═══
L('')
L('# Cell 3: 加载价格数据')
L('print("Loading price data...")')
L('')
L('# 批量获取日线')
L('price_fields = ["open", "close", "high", "low", "volume", "money"]')
L('raw_price = get_price(')
L('    ALL_STOCKS,')
L('    start_date=START_DATE,')
L('    end_date=END_DATE,')
L('    frequency="daily",')
L('    fields=price_fields,')
L('    fq="post",  # 后复权')
L('    skip_paused=False,')
L('    panel=False')
L(')')
L('print(f"Raw price: {raw_price.shape}")')
L('')
L('# 转成周频 (周五收盘)')
L("raw_price['week'] = raw_price.index.to_period('W')")
L('price_weekly = raw_price.groupby(["code", "week"]).last().reset_index()')
L('price_weekly = price_weekly.set_index("week").sort_index()')
L('weeks = sorted(price_weekly.index.unique())')
L('print(f"Weekly: {len(weeks)} weeks, {weeks[0]} ~ {weeks[-1]}")')
L('')
L('# 加载指数数据 (regime 检测用)')
L('INDEX_CODES = {"CSI300": "000300.XSHG", "CSI500": "000905.XSHG", "CSI_ALL": "000985.XSHG"}')
L('index_data = {}')
L('for name, code in INDEX_CODES.items():')
L('    px = get_price(code, start_date=START_DATE, end_date=END_DATE, frequency="daily", fields=["close"], fq="post")')
L('    index_data[name] = px')
L('    print(f"  {name}: {len(px)} days")')

# ═══ Cell 4: 基本面数据 ═══
L('')
L('# Cell 4: 加载基本面数据')
L('print("Loading fundamentals...")')
L('')
L('q = query(')
L('    valuation.code, valuation.market_cap, valuation.circulating_market_cap,')
L('    valuation.pb_ratio, valuation.ps_ratio, valuation.pe_ratio,')
L('    indicator.roe, indicator.roa, indicator.gross_profit_margin,')
L('    indicator.net_profit_margin, indicator.inc_revenue_year_on_year,')
L('    indicator.inc_net_profit_year_on_year,')
L('    balance.total_assets, balance.total_equity,')
L('    cash_flow.net_operate_cash_flow, cash_flow.net_profit,')
L('    income.total_operating_revenue, income.operating_profit')
L(')')
L('')
L('# 按季度获取')
L('fundamentals = {}')
L('for year in range(2021, 2027):')
L('    for qtr in range(1, 5):')
L('        date_str = f"{year}-{qtr*3:02d}-{28 if qtr!=4 else 31}"')
L('        if date_str > END_DATE:')
L('            break')
L('        try:')
L('            df = get_fundamentals(q, statDate=date_str)')
L('            if df is not None and len(df) > 0:')
L('                fundamentals[date_str] = df.set_index("code")')
L('        except:')
L('            pass')
L('print(f"Fundamental snapshots: {len(fundamentals)}")')
L('')
L('# 合并为因子可用格式')
L('def get_fundamental_for_stocks(stocks, date_str):')
L('    """获取某一期所有股票的基本面数据"""')
L('    # 找到最近的 snapshot')
L('    avail = sorted(fundamentals.keys())')
L('    target = None')
L('    for d in avail:')
L('        if d <= date_str:')
L('            target = d')
L('    if target is None:')
L('        return {}')
L('    df = fundamentals[target]')
L('    result = {}')
L('    for s in stocks:')
L('        if s in df.index:')
L('            row = df.loc[s]')
L('            result[s] = {')
L('                "market_cap": row.get("market_cap"),')
L('                "circ_mcap": row.get("circulating_market_cap"),')
L('                "pb": row.get("pb_ratio"),')
L('                "ps": row.get("ps_ratio"),')
L('                "roe": row.get("roe"),')
L('                "roa": row.get("roa"),')
L('                "gross_margin": row.get("gross_profit_margin"),')
L('                "net_margin": row.get("net_profit_margin"),')
L('                "rev_growth_yoy": row.get("inc_revenue_year_on_year"),')
L('                "earnings_growth_yoy": row.get("inc_net_profit_year_on_year"),')
L('                "total_assets": row.get("total_assets"),')
L('                "total_equity": row.get("total_equity"),')
L('                "ocf": row.get("net_operate_cash_flow"),')
L('                "net_income": row.get("net_profit"),')
L('                "revenue": row.get("total_operating_revenue"),')
L('                "operating_profit": row.get("operating_profit"),')
L('            }')
L('    return result')

# ═══ Cell 5: 因子计算函数 ═══
L('')
L('# Cell 5: 因子计算函数')
L('')
L('# 提取单周截面价格数据')
L('def build_price_data_slice(week_str, stock_list):')
L('    """为指定周构建 price_data dict (包含回看期数据)"""')
L('    week_idx = weeks.index(week_str)')
L('    lookback_start = max(0, week_idx - 52)  # 回看52周')
L('    hist_weeks = weeks[lookback_start:week_idx+1]')
L('    ')
L('    mask = (price_weekly["week"].isin(hist_weeks)) & (price_weekly["code"].isin(stock_list))')
L('    hist = price_weekly[mask]')
L('    ')
L('    result = {"close": {}, "open": {}, "high": {}, "low": {}, "volume": {}, "amount": {}}')
L('    for code in stock_list:')
L('        s_data = hist[hist["code"] == code]')
L('        if len(s_data) >= 10:')
L('            result["close"][code] = s_data["close"].values')
L('            result["open"][code] = s_data["open"].values')
L('            result["high"][code] = s_data["high"].values')
L('            result["volume"][code] = s_data["volume"].values')
L('            result["amount"][code] = s_data["money"].values')
L('    return result')
L('')

# 嵌入所有因子函数
for name in sorted(ALL_FACTORS.keys()):
    f = ALL_FACTORS[name]
    L(f['func'])
    L('')

L(f'# 所有已实现的因子: {len(ALL_FACTORS)}')
L(f'ALL_FACTOR_NAMES = {sorted(ALL_FACTORS.keys())}')
L(f'FACTOR_DIRECTIONS = { {n: ALL_FACTORS[n]["direction"] for n in ALL_FACTORS} }')

# ═══ Cell 6: Regime 检测 ═══
L('')
L('# Cell 6: Regime 检测')
L('def detect_regime(week_str):')
L('    """CSI500 vs CSI300 风格 + 全A趋势 → regime"""')
L('    for name in INDEX_CODES:')
L('        pass')
L('    ')
L('    csi300_rets = []')
L('    csi500_rets = []')
L('    csi_all_rets = []')
L('    ')
L('    for name, data in index_data.items():')
L('        w_ret = data["close"].resample("W").last().pct_change(4).dropna()')
L('        idx = w_ret.index.strftime("%Y-%m-%d")')
L('        if name == "CSI300":')
L('            csi300_rets = w_ret')
L('        elif name == "CSI500":')
L('            csi500_rets = w_ret')
L('        else:')
L('            csi_all_rets = w_ret')
L('    ')
L('    # 找到当前周对应的指数收益')
L('    week_date = pd.Timestamp(week_str)')
L('    ')
L('    if len(csi500_rets) == 0 or len(csi300_rets) == 0:')
L('        return "large_dominant"')
L('    ')
L('    style_spread = None; trend = None')
L('    for i, dt in enumerate(csi500_rets.index):')
L('        if dt >= week_date:')
L('            if i >= 4:')
L('                style_spread = csi500_rets.iloc[i] - csi300_rets.iloc[i]')
L('            if i >= 4 and len(csi_all_rets) > i:')
L('                trend = csi_all_rets.iloc[i]')
L('            break')
L('    ')
L('    if style_spread is None:')
L('        return "large_dominant"')
L('    ')
L('    if style_spread > STYLE_SPREAD_THRESHOLD and (trend is None or trend > TREND_THRESHOLD):')
L('        return "small_bull"')
L('    return "large_dominant"')

# ═══ Cell 7: ElasticNetCV per Regime ═══
L('')
L('# Cell 7: ElasticNetCV per Regime')
L('print("Computing factors and running ElasticNetCV...")')
L('')
L('MIN_WEEKS_FOR_REGIME = 20')
L('# 跳过前52周 (无足够回看数据)')
L('valid_weeks = weeks[52:]')
L('print(f"Valid weeks: {len(valid_weeks)}")')
L('')
L('# 按 regime 分组')
L('regime_weeks = {"large_dominant": [], "small_bull": []}')
L('for w in valid_weeks:')
L('    r = detect_regime(str(w))')
L('    regime_weeks[r].append(w)')
L('print(f"large_dominant: {len(regime_weeks[\'large_dominant\'])} weeks")')
L('print(f"small_bull: {len(regime_weeks[\'small_bull\'])} weeks")')
L('')
L('# 逐周计算因子 + forward return → 构建训练集')
L('def build_training_data(regime_name):')
L('    """为指定 regime 构建 X(factors) 和 y(forward return)"""')
L('    r_weeks = regime_weeks[regime_name]')
L('    if len(r_weeks) < MIN_WEEKS_FOR_REGIME:')
L('        return None, None')
L('    ')
L('    X_list, y_list = [], []')
L('    for w in r_weeks[:-1]:  # 最后一周没有 forward return')
L('        next_w_idx = weeks.index(w) + 1')
L('        if next_w_idx >= len(weeks):')
L('            continue')
L('        next_w = weeks[next_w_idx]')
L('        ')
L('        # 获取本周的活跃股票')
L('        mask = price_weekly["week"] == w')
L('        current_stocks = list(price_weekly[mask]["code"].unique())')
L('        if len(current_stocks) < 50:')
L('            continue')
L('        ')
L('        # 构建 price_data')
L('        pd_slice = build_price_data_slice(str(w), current_stocks[:500])  # 限500只控制内存')
L('        ')
L('        # 计算所有因子')
L('        factor_values = np.full((len(current_stocks[:500]), len(ALL_FACTOR_NAMES)), np.nan)')
L('        for j, fname in enumerate(ALL_FACTOR_NAMES):')
L('            try:')
L('                func = globals().get(f"compute_{fname}")')
L('                if func:')
L('                    arr, _ = func(current_stocks[:500], pd_slice)')
L('                    factor_values[:, j] = arr')
L('            except:')
L('                pass')
L('        ')
L('        # Forward return')
L('        mask_next = price_weekly["week"] == next_w')
L('        next_prices = price_weekly[mask_next].set_index("code")["close"]')
L('        curr_prices = price_weekly[mask].set_index("code")["close"]')
L('        ')
L('        fwd_ret = np.full(len(current_stocks[:500]), np.nan)')
L('        for i, s in enumerate(current_stocks[:500]):')
L('            if s in curr_prices.index and s in next_prices.index:')
L('                if curr_prices[s] > 0:')
L('                    fwd_ret[i] = next_prices[s] / curr_prices[s] - 1')
L('        ')
L('        X_list.append(factor_values)')
L('        y_list.append(fwd_ret)')
L('        ')
L('        if len(X_list) % 10 == 0:')
L('            print(f"  {regime_name}: {len(X_list)}/{len(r_weeks)} weeks processed")')
L('    ')
L('    if len(X_list) == 0:')
L('        return None, None')
L('    ')
L('    X = np.vstack(X_list)')
L('    y = np.hstack(y_list)')
L('    valid = np.isfinite(y) & np.all(np.isfinite(X), axis=1)')
L('    return X[valid], y[valid]')
L('')
L('# 训练')
L('for regime in ["large_dominant", "small_bull"]:')
L('    print(f"\\nTraining ElasticNetCV for {regime}...")')
L('    X, y = build_training_data(regime)')
L('    if X is None or len(X) < 100:')
L('        print(f"  Insufficient data: {len(X) if X is not None else 0} samples")')
L('        continue')
L('    ')
L('    print(f"  X: {X.shape}, y: {y.shape}")')
L('    ')
L('    # Standardize')
L('    scaler = StandardScaler()')
L('    X_scaled = scaler.fit_transform(X)')
L('    ')
L('    # ElasticNetCV')
L('    enet = ElasticNetCV(')
L('        l1_ratio=[.1, .5, .7, .9, .95, .99, 1],')
L('        cv=5,')
L('        max_iter=5000,')
L('        n_jobs=-1,')
L('        random_state=42')
L('    )')
L('    enet.fit(X_scaled, y)')
L('    ')
L('    print(f"  alpha={enet.alpha_:.6f}, l1_ratio={enet.l1_ratio_:.3f}")')
L('    print(f"  R2 (CV): {enet.score(X_scaled, y):.4f}")')
L('    ')
L('    # 输出权重')
L('    coef = enet.coef_')
L('    nonzero = np.abs(coef) > 1e-6')
L('    print(f"  Non-zero factors: {nonzero.sum()}/{len(coef)}")')
L('    ')
L('    weights = {}')
L('    for j in range(len(coef)):')
L('        if nonzero[j]:')
L('            fname = ALL_FACTOR_NAMES[j]')
L('            w = coef[j] * FACTOR_DIRECTIONS.get(fname, 1)')
L('            weights[fname] = float(w)')
L('            print(f"    {fname}: {w:+.6f}")')
L('    ')
L('    print(f"\\n  WEIGHTS_{regime.upper()} = {weights}")')
L('')
L('print("\\n✓ Complete! Copy the WEIGHTS dicts above to local JQGenerator.")')

# ═══ 写入文件 ═══
OUTPUT.parent.mkdir(exist_ok=True)
with open(OUTPUT, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))

print(f'\n✓ Written: {OUTPUT}')
print(f'  Lines: {len(lines)}')
print(f'  Factors: {len(ALL_FACTORS)}')
