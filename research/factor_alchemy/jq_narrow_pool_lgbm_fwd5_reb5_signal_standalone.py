def rebalance(context):
    g.trade_days += 1
    prev_date = context.previous_date.strftime('%Y-%m-%d')

    # ---- 结算上批 IC 样本: score vs open-to-open 收益 ----
    if g.pending_ic:
        for code, score, ref_open in g.pending_ic:
            o = _today_open(code)
            if o and ref_open and ref_open > 0:
                g.ic_samples.append((score, o / ref_open - 1.0))
        g.pending_ic = []

    if prev_date not in SIGNAL_TABLE:
        return   # 非重平衡日: 持仓不动

    target = SIGNAL_TABLE[prev_date]
    cd = get_current_data()

    # ---- 卖出: 不在目标名单的持仓清仓 (order_target 清仓语义含零股) ----
    sell_cnt = 0
    for s in list(context.portfolio.positions.keys()):
        if s in target:
            continue
        try:
            if cd[s].paused:
                continue   # 停牌卖不出, 下个重平衡日再试
            order_target(s, 0)
            sell_cnt += 1
        except Exception:
            pass

    # ---- 买入: 等权 8 只, 手数取整 order(s, lots*100), 跳过不足 100 股 ----
    w = context.portfolio.total_value / float(len(target))
    buy_cnt = 0
    for s, score in target.items():
        try:
            if s in context.portfolio.positions:
                continue
            if context.portfolio.available_cash < w * 0.5:
                break
            d = cd[s]
            if d.paused or d.is_st:
                continue
            px = d.day_open if (d.day_open and d.day_open > 0) else d.last_price
            if px <= 0:
                continue
            if d.high_limit <= d.last_price:
                continue   # 已涨停, 开盘买不进
            lots = int(w / px / 100)
            if lots < 1:
                continue   # 不足 100 股
            if is_kechuang(s):
                pc = _prev_close(s)
                if pc and pc > 0:
                    order(s, lots * 100, LimitOrderStyle(min(pc * 1.2, 9999)))
                else:
                    continue
            else:
                order(s, lots * 100)
            buy_cnt += 1
            # IC 样本: 用当日开盘价作为买入参考价
            o = _today_open(s)
            g.pending_ic.append((s, score, o))
        except Exception:
            pass

    g.turn_events.append((sell_cnt, buy_cnt))
    if g.trade_days % 25 == 0:
        log.info('reb | day=%d | prev_date=%s | sell=%d buy=%d | pos=%d | nav=%.0f'
                 % (g.trade_days, prev_date, sell_cnt, buy_cnt,
                    len(context.portfolio.positions), context.portfolio.total_value))


def _final_report(context):
    vals = np.array(g.daily_values)
    total_ret = vals[-1] / vals[0] - 1.0 if len(vals) > 1 else 0.0
    daily = np.diff(vals) / vals[:-1] if len(vals) > 1 else np.array([0.0])
    sharpe = float(daily.mean() / daily.std() * np.sqrt(252)) if daily.std() > 0 else 0.0
    peak = np.maximum.accumulate(vals)
    maxdd = float(np.min(vals / peak - 1.0)) if len(vals) else 0.0
    # 换手 (平均每次重平衡换出的仓位占比)
    tot_sell = _sum_vals(a for a, b in g.turn_events)
    tot_buy = _sum_vals(b for a, b in g.turn_events)
    n_reb = max(len(g.turn_events), 1)
    avg_turn_pct = 100.0 * (tot_sell + tot_buy) / (2.0 * TOP_K * n_reb)
    # 信号分 IC (score vs 买入次日 open-to-open 收益, 全体样本 spearman)
    ic_mean, ic_pos = 0.0, 0.0
    if len(g.ic_samples) >= 30:
        try:
            from scipy.stats import spearmanr
            sc = np.array([a for a, b in g.ic_samples])
            rt = np.array([b for a, b in g.ic_samples])
            ic_mean, _ = spearmanr(sc, rt)
            ic_pos = float(np.mean(rt > 0))
        except Exception:
            pass
    log.info('=' * 60)
    log.info('  [FINAL] narrow_pool_lgbm fwd5+EMA0.3+reb5 signal executor')
    log.info('=' * 60)
    log.info('  total_return_pct:  %.2f' % (total_ret * 100))
    log.info('  sharpe:            %.4f' % sharpe)
    log.info('  max_drawdown_pct:  %.2f' % (maxdd * 100))
    log.info('  rebal_days:        %d | avg_turn_per_reb: %.1f%%' % (n_reb, avg_turn_pct))
    log.info('  signal_rank_ic:    %.4f | ic>0_ratio: %.1f%% | n=%d'
             % (ic_mean, ic_pos * 100, len(g.ic_samples)))
    log.info('=' * 60)


def on_strategy_end(context):
    _final_report(context)
