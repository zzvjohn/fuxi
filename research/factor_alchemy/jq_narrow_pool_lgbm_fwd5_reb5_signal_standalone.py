def _prev_close(stock):
    try:
        # count=2 取 [-2]: 盘中 count=1 的 close 是当天实时价, 不是昨收
        h = attribute_history(stock, 2, '1d', ['close'], df=False)
        return float(h['close'][-2])
    except Exception:
        return None


def _today_open(stock):
    try:
        h = attribute_history(stock, 1, '1d', ['open'], df=False)
        return float(h['open'][0])
    except Exception:
        return None


