def behavior_label(ps):
    z = []
    for p in ps:
        k = behavior_kind(p) if isinstance(p, dict) else ''
        z.append((k == 'shadow') if k
                 else zero_adjudication(p['title'], p['detail']))
    if all(z):
        return '零裁决(影子/只记录)'
    if any(z):
        return '有效变更(含影子项)'
    return '有效变更'


def load_proposals():
    d = json.load(open(PROPOSALS, encoding='utf-8'))
    prods = d.get('proposals', d) if isinstance(d, dict) else d
    out = []
    for p in prods:
        st = str(p.get('status') or '').lower()
        if st not in DONE_STATUS:
            continue
        pid = str(p.get('proposal_id') or '')
        m = re.match(r'P-(\d{8})', pid)
        if not m:
            continue
        day = m.group(1)
        out.append({
            'proposal_id': pid,
            'date': '%s-%s-%s' % (day[:4], day[4:6], day[6:8]),
            'day': day,
            'status': st,
            'title': str(p.get('title') or '')[:120],
            'category': str(p.get('category') or ''),
            'detail': str(p.get('landed_detail') or p.get('implementation') or '')[:200],
            # 显式声明通道 (2026-09-15): 有则优先于关键词自动判定
            'domains': p.get('domains'),
            'proposal_change_kind': p.get('proposal_change_kind'),
        })
    out.sort(key=lambda x: (x['date'], x['proposal_id']))
    return out


def group_by_day(proposals):
    g = {}
    for p in proposals:
        g.setdefault(p['date'], []).append(p)
    return g


def load_registry():
    if os.path.exists(REGISTRY):
        return json.load(open(REGISTRY, encoding='utf-8'))
    return {'policy': {}, 'versions': list(OFFICIAL)}


def covered_ids(reg):
    s = set()
    for v in reg['versions']:
        for p in v.get('proposals', []):
            s.add(p if isinstance(p, str) else p.get('proposal_id'))
    return s


def next_patch(reg):
    mx = 2
    for v in reg['versions']:
        m = re.match(r'v0\.7\.(\d+)$', v['version'])
        if m:
            mx = max(mx, int(m.group(1)))
    return mx + 1


def behavior_kind(p):
    """提案显式声明的变更性质: 'shadow'(只记录) | 'behavior'(真实改变行为)。

    缺省时回退关键词自动判定 (zero_adjudication)。显式声明的存在意义:
    自动判定是**子串匹配**, 会被否定式表述误触发 ——
    实测 2026-09-15 P-20260915-006 文案含「非影子」⇒ 被误判为零裁决。
    """
    k = str(p.get('proposal_change_kind') or '').strip().lower()
    return k if k in ('shadow', 'behavior') else ''


def _prop_domains(p):
    """优先用提案显式声明的 domains, 否则按关键词 classify()。"""
    d = p.get('domains')
    if isinstance(d, list) and d:
        return [str(x) for x in d]
    return classify(p['title'], p['category'], p['detail'])


def mk_prop(p):
    k = behavior_kind(p)
    return {
        'proposal_id': p['proposal_id'], 'title': p['title'], 'status': p['status'],
        'domains': _prop_domains(p),
        'zero_adjudication': (k == 'shadow') if k else zero_adjudication(p['title'], p['detail']),
    }


def official_version_for(date):
    """官方版本归属: <08-31 → v0.7.0(开发期), 08-31 → v0.7.1, 09-01 → v0.7.2"""
    if date < '2026-08-31':
        return 'v0.7.0'
    if date == '2026-08-31':
        return 'v0.7.1'
    if date == '2026-09-01':
        return 'v0.7.2'
    return None


def rebuild(proposals, reg):
    """按提案库重建: 官方 3 版归属历史提案, v0.7.3+ 按日批次编号"""
    versions = [dict(v) for v in OFFICIAL]
    byver = {v['version']: v for v in versions}
    for v in byver.values():
        v['proposals'] = []

    g = group_by_day(proposals)
    for d in sorted(g):
        tgt = official_version_for(d)
        if tgt:
            byver[tgt]['proposals'].extend(mk_prop(p) for p in g[d])

    patch = 3
    for d in sorted(g):
        if official_version_for(d):
            continue
        ps = g[d]
        domains = []
        for p in ps:
            for h in _prop_domains(p):
                if h not in domains:
                    domains.append(h)
        zero = all(
            (behavior_kind(p) == 'shadow') if behavior_kind(p)
            else zero_adjudication(p['title'], p['detail'])
            for p in ps)
        versions.append({
            'version': 'v0.7.%d' % patch,
            'date': d,
            'official': False,
            'title': ' / '.join(p['title'][:44] for p in ps[:3]) + ('…' if len(ps) > 3 else ''),
            'proposals': [mk_prop(p) for p in ps],
            'domains': domains,
            'landmark': LANDMARK.get(d, ''),
            'behavior': behavior_label(ps),
            'rollback': '开关/环境变量回退' if not zero else '无需回退(零副作用)',
        })
        patch += 1
    for v in versions:
        if v.get('official'):
            v.setdefault('domains', [])
            v.setdefault('landmark', LANDMARK.get(v['date'], ''))
            v['behavior'] = '官方发布'
            v.setdefault('rollback', '—')
    reg['versions'] = versions
    return reg


